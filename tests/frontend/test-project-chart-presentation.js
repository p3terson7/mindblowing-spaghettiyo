const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const read = name => fs.readFileSync(path.resolve(__dirname, "../..", name), "utf8");
const utilities = read("app/frontend/scripts/Utilities.js");
const projects = read("app/frontend/scripts/Views/ProjectsView.js");
const css = read("app/frontend/assets/apple-ui.css");
const html = read("app/frontend/index.html");
assert(html.includes('<section class="project-analytics-bar" id="projectAnalyticsBar"'), "Project summary must not keep its enclosing panel surface.");
assert(!html.includes('class="panel-kicker" data-i18n="projects.analytics"'), "The compact project summary should not have a redundant heading.");
assert.match(css, /\.project-analytics-bar\s*\{\s*background: transparent;\s*border: 0;\s*box-shadow: none;/);
const stage = { innerHTML: "", attributes: {}, setAttribute(key, value) { this.attributes[key] = value; } };
const context = { t: () => "Chargement…", escapeHtml: value => String(value), document: { getElementById: () => ({ querySelector: () => stage }) } };
vm.createContext(context);
vm.runInContext(utilities.slice(utilities.indexOf("function createLoadingState("), utilities.indexOf("function getStatusTone(")), context);
for (const variant of ["chartLine", "chartDonut"]) {
  const result = context.createLoadingState(variant);
  assert(result.includes("<svg") && result.includes("Chargement…"));
  assert(!result.includes("loading-bar-chart") && !result.includes("loading-bar-title"), "A new chart loader uses the old filled blobs.");
}
assert(context.createLoadingState("chartLine").includes("chart-placeholder-grid"));
assert(context.createLoadingState("chartDonut").includes("chart-placeholder-ring-progress"));
context.setChartLoadingState("chart", "chartLine");
assert.equal(stage.attributes["aria-busy"], "true");
assert(stage.innerHTML.includes("chart-placeholder-line"));
context.setChartLoadingState("chart");
assert(stage.innerHTML.includes("loading-shell-chart"), "Other chart callers must keep their existing default.");
assert(projects.includes('setChartLoadingState("projectChartContainer", "chartLine")'));
assert(projects.includes('createLoadingState("chartDonut", 1)'));
const pieStages = ["pie1", "pie2"].map(id => ({ ...stage, attributes: {}, getAttribute: () => id, innerHTML: "old canvas" }));
const destroyed = [], cancelled = [];
const summaryTarget = { innerHTML: "" };
context.document.getElementById = () => summaryTarget;
context.pendingProjectInsightFrameId = 7;
context.window = { cancelAnimationFrame: id => cancelled.push(id) };
context.document.querySelectorAll = () => pieStages;
context.destroyProjectInsightChart = id => destroyed.push(id);
context.setLoadingState = () => {};
vm.runInContext(projects.slice(projects.indexOf("function setProjectInsightsLoadingState()"), projects.indexOf("function getProjectChartTheme()")), context);
context.setProjectInsightsLoadingState();
assert(context.document.getElementById("projectInsightsSummary").innerHTML.includes("project-insight-stat-loading"), "Summary loading must use its compact plain metrics.");
assert.deepEqual(destroyed, ["pie1", "pie2"], "Old pie charts must be destroyed before replacing their canvas.");
assert.deepEqual(cancelled, [7], "A pending pie render must not replace newer loading placeholders.");
assert(pieStages.every(element => element.innerHTML.includes("chart-placeholder-donut") && element.attributes["aria-busy"] === "true"));
assert.match(css, /#projectChartContainer \.chart-stage\s*\{\s*min-height: 560px;\s*height: clamp\(560px, 68vh, 800px\)/);
assert.match(css, /\.chart-placeholder-ring circle\s*\{ fill: none; stroke-width: 3;/);
assert.match(css, /\.chart-placeholder-ring-progress,\s*\.chart-placeholder-dot\s*\{ animation: none !important;/);
console.log("Chart presentation passed: taller plot, lightweight SVG loaders, busy state, reduced motion and unchanged generic loaders.");
